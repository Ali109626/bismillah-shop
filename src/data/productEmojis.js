/**
 * Get the color and emoji theme for a category
 */
export function getCategoryTheme(category) {
  if (!category) return defaultTheme;
  const cleanCat = category.trim();
  return categoryThemes[cleanCat] || defaultTheme;
}

/**
 * Look up a product emoji by product name (case-insensitive fuzzy match),
 * falling back to category theme emoji if not specifically matched.
 */
export function getProductEmoji(productName, category = 'Grocery') {
  if (!productName) {
    return getCategoryTheme(category).emoji;
  }

  const cleanName = productName.trim().toLowerCase();

  // 1. Direct exact match
  const exactKey = Object.keys(productEmojis).find(k => k.toLowerCase() === cleanName);
  if (exactKey) {
    return productEmojis[exactKey];
  }

  // 2. Substring match (sort keys longest first so "Basmati Rice" matches before "Rice")
  const sortedKeys = Object.keys(productEmojis).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    const kLow = key.toLowerCase();
    if (cleanName.includes(kLow) || kLow.includes(cleanName)) {
      return productEmojis[key];
    }
  }

  // 3. Fallback to category default emoji
  return getCategoryTheme(category).emoji;
}

