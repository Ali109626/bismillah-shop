/**
 * Automatically determine the most suitable product category from product name
 * Covers English, Roman Urdu, and Urdu Kiryana terms.
 *
 * @param {string} productName
 * @returns {'Grocery' | 'Dairy' | 'Snacks' | 'Beverages' | 'Household' | 'Personal Care'}
 */
export function getProductCategory(productName) {
  const n = (productName || '').toLowerCase().trim();
  if (!n) return 'Grocery';

  // 1. Snacks & Confectionery (checked before dairy to avoid "Dairy Milk" chocolate matching dairy)
  if (/\b(chocolate|dairy milk|kitkat|snickers|biscuit|biscuits|cookie|cookies|sooper|marie|rio|oreo|tuc|prince|gala|wafer|chips|lays|kurkure|cheetos|nimko|dal moth|peanuts|bread|bun|rusk|papey|cake|cupcake|muffin|egg|eggs|anday|candy|toffee|bubble|chocolatto)\b/.test(n) ||
      /(?:^|[\s،,])(?:بسکٹ|چپس|کیک|رس|ڈبل روٹی|انڈے|انڈا|ٹافی|چاکلیٹ|نمکو)(?:[\s،,]|$)/.test(n) ||
      n.includes('chocolate') || n.includes('biscuit') || n.includes('cookie') || n.includes('chips') || n.includes('lays') || n.includes('nimko') || n.includes('rusk') || n.includes('cake') || n.includes('egg') || n.includes('anday') || n.includes('bread')) {
    return 'Snacks';
  }

  // 2. Dairy (Milk, Butter, Cheese, Yogurt, Cream, Lassi)
  if (/\b(milk|doodh|cream|butter|makhan|yogurt|dahi|cheese|paneer|olpers|milkpak|everyday|tarang|nido|nurpur|haleeb|khoya|lassi)\b/.test(n) ||
      /(?:^|[\s،,])(?:دودھ|دہی|مکھن|پنیر|ملائی|لسی|کھویا)(?:[\s،,]|$)/.test(n) ||
      n.includes('milk') || n.includes('doodh') || n.includes('yogurt') || n.includes('dahi') || n.includes('olpers') || n.includes('milkpak')) {
    return 'Dairy';
  }

  // 3. Beverages & Tea (Chai, Cold drinks, Juices, Sharbat, Water)
  if (/\b(tea|chai|patti|teabag|teabags|tapal|lipton|vital|kawa|kahwa|green tea|coffee|nescafe|rooh afza|jam-e-shirin|sharbat|juice|tang|fruita vitals|pepsi|coke|coca cola|7up|seven up|sprite|dew|mountain dew|fanta|mirinda|marinda|sting|red bull|pakola|soda|water|aquafina|cold drink)\b/.test(n) ||
      /(?:^|[\s،,])(?:چائے|پتی|شربت|مشروب|جوس|روح افزا|پانی|کولا)(?:[\s،,]|$)/.test(n) ||
      n.includes('tea') || n.includes('chai') || n.includes('patti') || n.includes('juice') || n.includes('pepsi') || n.includes('coke') || n.includes('sprite') || n.includes('sharbat') || n.includes('rooh afza')) {
    return 'Beverages';
  }

  // 4. Personal Care (Soaps, Shampoos, Toothpaste, Lotions, Hygiene)
  if (/\b(soap|sabun|lifebuoy|lux|dettol|safeguard|santoor|dove|tibet|shampoo|conditioner|sunsilk|pantene|head & shoulders|toothpaste|colgate|closeup|sensodyne|medicam|toothbrush|razor|gillette|blade|lotion|vaseline|fair & lovely|glow & lovely|ponds|powder|hair oil|parachute|sanitary|pads|diaper|pampers|facewash|face wash|body wash|hand wash)\b/.test(n) ||
      /(?:^|[\s،,])(?:صابن|شیمپو|ٹوٹھ پیسٹ|مسواک|برش|لوشن|ڈائپر)(?:[\s،,]|$)/.test(n) ||
      n.includes('soap') || n.includes('sabun') || n.includes('shampoo') || n.includes('toothpaste') || n.includes('toothbrush') || n.includes('facewash') || n.includes('face wash') || n.includes('lotion')) {
    return 'Personal Care';
  }

  // 5. Household & Cleaning (Detergents, Surface Cleaners, Brooms, Matches)
  if (/\b(surf|detergent|ariel|bonus|express|bright|wheel|tide|vim|dishwash|lemon max|harpic|bleach|robin blue|neel|phenyle|phenyl|cleaner|colin|mop|wiper|broom|jharoo|dustpan|sponge|scrubber|tissue|tissues|rose petal|toilet roll|foil|matches|matchbox|maachis|mortein|king tox)\b/.test(n) ||
      /(?:^|[\s،,])(?:سرف|ڈٹرجنٹ|جھاڑو|فینائل|ماچس|ٹشو|پوچھا)(?:[\s،,]|$)/.test(n) ||
      n.includes('surf') || n.includes('detergent') || n.includes('dishwash') || n.includes('harpic') || n.includes('bleach') || n.includes('phenyle') || n.includes('jharoo') || n.includes('broom') || n.includes('tissue')) {
    return 'Household';
  }

  // 6. Default: Grocery (Rice, Flour, Atta, Ghee, Oil, Sugar, Daal, Spices, Salt)
  return 'Grocery';
}

/**
 * Automatically determine the standard Kiryana unit / weight from product name & category
 * Covers Pakistani retail units: 1 Liter, 1 kg, 1 Piece, 1 Pack, 1 Dozen, 1 Bottle, 1 Box.
 *
 * @param {string} productName
 * @param {string} [category='Grocery']
 * @returns {string} e.g. '1 Liter', '1 kg', '1 Piece', '1 Pack', '1 Dozen', '1 Bottle'
 */
export function getProductUnit(productName, category = 'Grocery') {
  const n = (productName || '').toLowerCase().trim();
  if (!n) {
    if (category === 'Dairy' || category === 'Beverages') return '1 Liter';
    if (category === 'Snacks') return '1 Pack';
    if (category === 'Household' || category === 'Personal Care') return '1 Piece';
    return '1 kg';
  }

  // 1. Eggs & Bananas -> 1 Dozen
  if (/\b(egg|eggs|anday|desi anday|banana|kela|keley)\b/.test(n) ||
      /(?:^|[\s،,])(?:انڈے|انڈا|کیلے|کیلا)(?:[\s،,]|$)/.test(n) ||
      n.includes('egg') || n.includes('anday')) {
    return '1 Dozen';
  }

  // 2. Packets & Confectionery: Chocolates, Biscuits, Chips, Snacks, Tea, Bread, Rusk, Masala, Tissues, Butter, Cheese, Pads
  if (/\b(chocolate|dairy milk|kitkat|snickers|candy|toffee|biscuit|biscuits|cookie|cookies|sooper|marie|rio|oreo|tuc|prince|gala|wafer|chips|lays|kurkure|cheetos|nimko|dal moth|peanuts|bread|bun|rusk|papey|cake|cupcake|tea|chai|patti|teabag|teabags|tapal|lipton|vital|shan|masala|tissue|tissues|rose petal|diaper|pampers|pads|noodles|pasta|macaroni|spaghetti|seviyan|butter|cheese|paneer)\b/.test(n) ||
      /(?:^|[\s،,])(?:بسکٹ|چپس|کیک|رس|ڈبل روٹی|ٹافی|چاکلیٹ|نمکو|چائے|پتی|ٹشو|مکھن|پنیر)(?:[\s،,]|$)/.test(n) ||
      n.includes('chocolate') || n.includes('biscuit') || n.includes('chips') || n.includes('lays') || n.includes('tea') || n.includes('chai') || n.includes('patti') || n.includes('bread') || n.includes('rusk') || n.includes('tissue') || n.includes('noodles') || n.includes('pasta') || n.includes('masala') || n.includes('butter') || n.includes('cheese')) {
    return '1 Pack';
  }

  // 3. Bottles: Shampoos, Lotions, Hand wash, Harpic, Dishwash liquid, Ketchup, Sauces
  if (/\b(shampoo|conditioner|lotion|vaseline|hair oil|parachute|hand wash|facewash|face wash|body wash|harpic|liquid|ketchup|sauce|mayo|mayonnaise|jam|honey|shehad)\b/.test(n) ||
      /(?:^|[\s،,])(?:شیمپو|لوشن|شہد|جام)(?:[\s،,]|$)/.test(n) ||
      n.includes('shampoo') || n.includes('conditioner') || n.includes('lotion') || n.includes('hand wash') || n.includes('face wash') || n.includes('facewash') || n.includes('harpic') || n.includes('ketchup') || n.includes('liquid')) {
    return '1 Bottle';
  }

  // 4. Pieces: Soap, Toothbrush, Razor, Vim bar, Broom, Matches
  if (/\b(soap|sabun|lifebuoy|lux|dettol|safeguard|santoor|dove|toothbrush|razor|blade|gillette|broom|jharoo|mop|wiper|scrubber|sponge|steel wool)\b/.test(n) ||
      /(?:^|[\s،,])(?:صابن|جھاڑو|برش)(?:[\s،,]|$)/.test(n) ||
      n.includes('soap') || n.includes('sabun') || n.includes('toothbrush') || n.includes('razor') || n.includes('blade') || n.includes('broom') || n.includes('jharoo') || n.includes('vim bar') || n.includes('dishwash bar') || n.includes('max bar')) {
    return '1 Piece';
  }

  if (/\b(matches|matchbox|maachis)\b/.test(n) || /(?:^|[\s،,])(?:ماچس)(?:[\s،,]|$)/.test(n) || n.includes('match')) {
    return '1 Box';
  }

  // 5. Liquids & Oils -> 1 Liter
  if (/\b(oil|tail|sarson|mustard oil|cooking oil|canola|sunflower)\b/.test(n) ||
      /\b(milk|doodh|milkpak|olpers|everyday|tarang|nurpur|haleeb)\b/.test(n) ||
      /\b(sharbat|rooh afza|syrup|vinegar|sirka|bleach|phenyle|phenyl)\b/.test(n) ||
      /(?:^|[\s،,])(?:تیل|دودھ|شربت|فینائل|سرکہ)(?:[\s،,]|$)/.test(n) ||
      n.includes(' oil') || n.startsWith('oil') || n.includes('tail') || n.includes('milk') || n.includes('doodh') || n.includes('sharbat') || n.includes('phenyle') || n.includes('bleach')) {
    return '1 Liter';
  }

  // Cold drinks & Bottled Water -> 1.5 Liter
  if (/\b(pepsi|coke|coca cola|sprite|7up|seven up|dew|fanta|mirinda|marinda|sting|water|aquafina|cold drink|soda)\b/.test(n) ||
      /(?:^|[\s،,])(?:پانی|کولڈ ڈرنک)(?:[\s،,]|$)/.test(n) ||
      n.includes('pepsi') || n.includes('coke') || n.includes('sprite') || n.includes('water')) {
    return '1.5 Liter';
  }

  // Juices -> 1 Liter
  if (n.includes('juice') || n.includes('tang') || n.includes('جوس')) {
    return '1 Liter';
  }

  // 6. Bulk items & Grains (Default Grocery, Ghee, Sugar, Rice, Flour & Detergents) -> 1 kg
  if (/\b(rice|chawal|basmati|tota|sella|atta|flour|wheat|gandham|maida|suji|besan|sugar|cheeni|gur|shakar|ghee|banaspati|daal|dal|chana|moong|masoor|mash|lobia|salt|namak|surf|detergent|ariel|bonus|wheel|express|potato|aloo|onion|pyaz|tomato|tamatar|ginger|adrak|garlic|lehsan|dahi|yogurt)\b/.test(n) ||
      /(?:^|[\s،,])(?:چاول|چینی|آٹا|گھی|دال|نمک|سرف|دہی|آلو|پیاز|ٹماٹر)(?:[\s،,]|$)/.test(n) ||
      n.includes('rice') || n.includes('chawal') || n.includes('sugar') || n.includes('cheeni') || n.includes('atta') || n.includes('flour') || n.includes('daal') || n.includes('dal') || n.includes('ghee') || n.includes('salt') || n.includes('namak') || n.includes('surf') || n.includes('detergent')) {
    return '1 kg';
  }

  // 7. Category defaults fallback
  if (category === 'Dairy') return '1 Liter';
  if (category === 'Beverages') return '1 Liter';
  if (category === 'Snacks') return '1 Pack';
  if (category === 'Household') return '1 Piece';
  if (category === 'Personal Care') return '1 Piece';
  return '1 kg';
}

